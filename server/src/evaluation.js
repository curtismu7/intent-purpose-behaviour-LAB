// Scenario, baseline and custom-call evaluation, in both modes. MOCK reads stored signals from mockTable.json and runs only decide().
// LIVE runs the real engine. The two must agree on the default policy: a test replays every table row through the live engine.
import { fillDeep, VERTICALS } from './cast.js';
import { BASELINE_SCRIPT, PURPOSE_PROFILE, SCENARIOS, baselineCall, seedCalls } from './data.js';
import { decide } from './decide.js';
import { evaluateLive, learnerFrom, liveSignals, shouldLearn } from './engine.js';
import { observe, withPhase } from './behaviour.js';
import { applyFloor } from './intent.js';
import { clonePolicy } from './policy.js';
import { OBO_SCENARIOS, IDJAG_SCENARIOS, runIdJag, runObo } from './oauth.js';
import { normalizeCall } from './call.js';

// The table stores what was SEEN (raw similarity scores, behaviour departure and calls seen); the policy then decides what counts, so
// an edited Floor, MinObservations or EnforceObservations changes a Mock row the same way it changes a Live one.
function hydrate(stored, policy) {
  const semantic = { ...applyFloor(stored.intent.semantic.rawScores, policy.intent.Floor), hits: undefined };
  return { ...stored, intent: { ...stored.intent, semantic, class: stored.intent.deterministic.matched.length ? stored.intent.deterministic.matched[0].class : semantic.class }, behaviour: withPhase(stored.behaviour, policy) };
}
// Live signals computed with Floor 0 and no policy-dependent behaviour fields, ready to store.
const storable = (call, ctx) => {
  const s = liveSignals(call, { ...ctx, policy: { ...ctx.policy, intent: { ...ctx.policy.intent, Floor: 0 } } });
  const { raw, callsSeen, components } = s.behaviour;
  return { intent: { ...s.intent, semantic: { ...s.intent.semantic, hits: undefined, scores: undefined } }, purpose: s.purpose, behaviour: { raw, callsSeen, components } };
};

export const scenarioFor = (cast, id) => { const s = SCENARIOS.find((x) => x.id === id); return s ? fillDeep(s, cast) : null; };
export const declarationFor = (cast, declares) => (declares ? fillDeep(PURPOSE_PROFILE, cast) : null);

export function evaluateScenario({ cast, vertical, id, mode, policy, table }) {
  const sc = scenarioFor(cast, id);
  if (!sc) return null;
  const declaration = declarationFor(cast, sc.declares);
  const call = normalizeCall(sc.call);
  let signals; let out;
  if (mode === 'live') {
    out = evaluateLive(call, { declaration, learner: learnerFrom(seedCalls(cast, sc.seed)), policy });
    signals = out.signals;
  } else {
    signals = hydrate(table.scenarios[vertical][id], policy);
    out = { signals, ...decide(signals, policy) };
  }
  return { mode, scenario: id, title: sc.title, lesson: sc.lesson, agent: sc.agent, declaration, call, expectedWithDefaultPolicy: sc.expected, ...out };
}

// A call of the visitor's own: Live only (there is no table for it). Judged as the scenarios' main agent, with its usual history.
export function evaluateCustom({ cast, input, policy }) {
  const call = normalizeCall(input);
  const declaration = declarationFor(cast, true);
  const out = evaluateLive(call, { declaration, learner: learnerFrom(seedCalls(cast, 24)), policy });
  return { mode: 'live', scenario: 'custom', title: 'Your own call', lesson: 'Judged as the lab\'s main agent, with its usual history of 24 calls.', agent: cast.castAgentId, declaration, call, ...out };
}

export const baselineRows = ({ cast, vertical, policy, table }) => BASELINE_SCRIPT.map((kind, i) => {
  const signals = hydrate(table.baseline[vertical][i], policy);
  return { n: i + 1, kind, call: baselineCall(cast, kind, i), signals, ...decide(signals, policy) };
});

// One Live baseline call: real engine, the workspace's own learner. A call the engine refused or held is NOT learned.
export function fireBaseline({ cast, kind, policy, state }) {
  const call = normalizeCall(baselineCall(cast, kind, state.counter));
  if (!call) return null;
  const out = evaluateLive(call, { declaration: declarationFor(cast, true), learner: state.learner, policy });
  const learned = shouldLearn(out.decision);
  if (learned) observe(state.learner, call, policy);
  state.counter += 1;
  return { n: state.counter, kind, call, learned, ...out };
}

// Build the whole mock table from the live engine (npm run mock-table). Deterministic: no clocks in the stored values.
export function buildMockTable() {
  const policy = clonePolicy();
  const table = { schema: 'ipb-mock-table/1', note: 'Generated by scripts/build-mock-table.mjs from the live engine. Do not edit by hand.', scenarios: {}, baseline: {}, obo: {}, idjag: {} };
  for (const [vertical, cast] of Object.entries(VERTICALS)) {
    table.scenarios[vertical] = Object.fromEntries(SCENARIOS.map((s) => {
      const sc = scenarioFor(cast, s.id);
      return [s.id, storable(normalizeCall(sc.call), { declaration: declarationFor(cast, sc.declares), learner: learnerFrom(seedCalls(cast, sc.seed)), policy })];
    }));
    const learner = learnerFrom([]);
    table.baseline[vertical] = BASELINE_SCRIPT.map((kind, i) => {
      const call = normalizeCall(baselineCall(cast, kind, i));
      const ctx = { declaration: declarationFor(cast, true), learner, policy };
      const row = storable(call, ctx);
      if (shouldLearn(evaluateLive(call, ctx).decision)) observe(learner, call, policy);
      return row;
    });
  }
  const cast = VERTICALS.finance;
  const flags = (res) => Object.fromEntries(res.checks.map((c) => [c.id, c.ok]));
  for (const s of OBO_SCENARIOS) { const r = runObo({ cast, scenario: s.id, mode: 'live' }); table.obo[s.id] = { gateway: flags(r.gatewayChecks), backend: flags(r.backend) }; }
  for (const s of IDJAG_SCENARIOS) {
    const r = runIdJag({ cast, scenario: s.id, mode: 'live' });
    table.idjag[s.id] = { first: flags(r.redeem), ...(r.redeemAgain ? { second: flags(r.redeemAgain) } : {}), ...(r.api ? { api: flags(r.api) } : {}) };
  }
  return table;
}
